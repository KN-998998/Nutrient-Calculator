def _load_db() -> tuple[list[dict], dict[str, list[dict]]]:
    rows = list(csv.DictReader(NUTRIENT_DB.open(encoding="utf-8-sig")))
    by_name: dict[str, list[dict]] = {}
    for r in rows:
        by_name.setdefault(r["ingredient_name"], []).append(r)
    return rows, by_name


def resolve_ingredient(by_name: dict[str, list[dict]], name: str) -> tuple[str, str]:
    """把食材名解析为 (编码, 名称)。优先取编码全局唯一的行(避免重复编码消歧失败)。"""
    rows = by_name.get(name)
    if not rows:
        return "", name  # 库外食材: 留空编码, 由匹配层标记
    if len(rows) == 1:
        return rows[0]["ingredient_code"], rows[0]["ingredient_name"]
    from collections import Counter
    code_count = Counter(r["ingredient_code"] for row_list in by_name.values() for r in row_list)
    for r in rows:
        if code_count[r["ingredient_code"]] == 1:
            return r["ingredient_code"], r["ingredient_name"]
    # 全部重码: 已知多行同名食材用手工指定编码(如 清水→VHF024, 否则名称消歧失败)
    if name in NAME_CODE_OVERRIDE:
        return NAME_CODE_OVERRIDE[name], name
    return rows[0]["ingredient_code"], rows[0]["ingredient_name"]  # 其余取首行


def generate(path: Path) -> dict:
    _, by_name = _load_db()
    wb = Workbook()
    wb.remove(wb.active)
    stats = {"dishes": 0, "ingredients": 0, "unmatched_names": [], "sheets": []}
    for meal, dishes in DISHES.items():
        ws = wb.create_sheet(f"5月{meal}餐配料sop")
        ws.append(HEADER)
        for date_label, dish_name, components in dishes:
            stats["dishes"] += 1
            total_oz = 0.0
            total_g = 0.0
            first_row = True
            for component_name, ingredients in components:
                for idx, (ing_name, oz) in enumerate(ingredients):
                    code, resolved_name = resolve_ingredient(by_name, ing_name)
                    if resolved_name != ing_name or not code:
                        stats["unmatched_names"].append(ing_name)
                    grams = round(oz * OZ_TO_G, 3)
                    total_oz += oz
                    total_g += grams
                    ws.append([
                        date_label if first_row else "",
                        dish_name if first_row else "",
                        component_name if idx == 0 else "",
                        resolved_name,
                        oz,
                        grams,
                        code,
                        SPEC.get(resolved_name, ""),
                    ])
                    first_row = False
                    stats["ingredients"] += 1
            ws.append(["", "", "", "合計生重", round(total_oz, 2), round(total_g, 3), "", ""])
        stats["sheets"].append(ws.title)
    wb.save(path)
    return stats


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("output", type=Path, nargs="?", default=PROJECT_ROOT / "data" / "samples" / "拟真菜单SOP_5月测试.xlsx")
    args = ap.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    stats = generate(args.output)
    print(f"已生成: {args.output}")
    print(f"  sheets: {', '.join(stats['sheets'])}")
    print(f"  菜式: {stats['dishes']}  配料行: {stats['ingredients']}")
    if stats["unmatched_names"]:
        print(f"  ⚠ 库外食材(将 unmatched): {sorted(set(stats['unmatched_names']))}")
    else:
        print("  所有食材均在营养库内")
    return 0


if __name__ == "__main__":
    sys.exit(main())
